int Driver::runCLI(int argc, char* argv[]) {
    if (argc < 2) {
        std::cerr << "Error: no command provided.'\n";
        return 1;
    }

    const auto command = readCommand(argv[1]);

    switch (command) {
        case CLICommand::HELP: {
            if (argc > 3) {
                std::cerr << "Error: too many arguments.'\n";
                return 1;
            }
            help();
            return 0;
        }

        case CLICommand::EXECUTE: {
            if (argc < 3) {
                std::cerr << "Error: no file path provided'\n";
                return 1;
            }
            if (argc > 3) {
                std::cerr << "Error: too many arguments.'\n";
                return 1;
            }
            return execute(argv[2]);
        }

        case CLICommand::ASSEMBLE: {
            if (argc < 3) {
                std::cerr << "Error: no file path provided'\n";
                return 1;
            }
            if (argc > 3) {
                std::cerr << "Error: too many arguments.'\n";
                return 1;
            }
            return assemble(argv[2]);
        }

        case CLICommand::COMPILE: {
            if (argc < 3) {
                std::cerr << "Error: no file path provided'\n";
                return 1;
            }
            if (argc > 4) {
                std::cerr << "Error: too many arguments.'\n";
                return 1;
            }

            const auto commandOptions = readCommandOptions(command, argc, argv);

            return compile(argv[2], commandOptions.optimisationLevel);
        }

        case CLICommand::RUN: {
            if (argc < 3) {
                std::cerr << "Error: no file path provided'\n";
                return 1;
            }
            if (argc > 6) {
                std::cerr << "Error: too many arguments.'\n";
                return 1;
            }

            const CLICommandOptions commandOptions = readCommandOptions(command, argc, argv);

            return run(argv[argc - 1], commandOptions.outputAssembly, commandOptions.outputBytecode, commandOptions.optimisationLevel);
        }
    }
    return 1;
}

CLICommand Driver::readCommand(const std::string& command) {
    if (command == "help") return CLICommand::HELP;
    if (command == "execute") return CLICommand::EXECUTE;
    if (command == "assemble") return CLICommand::ASSEMBLE;
    if (command == "compile") return CLICommand::COMPILE;
    if (command == "run") return CLICommand::RUN;

    std::cerr << "Unknown command: " << command << std::endl;
    exit(1);
}

CLICommandOptions Driver::readCommandOptions(const CLICommand command, const int argc, char* argv[]) {
    CLICommandOptions options;
    for (int i = 2; i < argc - 1; i++) {
        const std::string_view arg = argv[i];

        if (arg == "-a" || arg == "-b") {
            if (command != CLICommand::RUN) {
                // invalid option for command type
                commandOptionError("Invalid command option '" + std::string(arg) + "'");
            }

            bool& outputOption = arg == "-a" ? options.outputAssembly : options.outputBytecode;

            if (outputOption) {
                commandOptionError("Duplicate command option '" + std::string(arg) + "'");
            }

            outputOption = true;
        }

        else if (arg == "-O0") {
            if (options.optimisationLevel == OptimisationLevel::O0) {
                commandOptionError("Duplicate command option '-O0'");
            }
            options.optimisationLevel = OptimisationLevel::O0;
        }

        else { // read file
            commandOptionError("Unknown command option '" + std::string(arg) + "'");
        }
    }
    return options;
}

void Driver::commandOptionError(const std::string &message) {
    std::cerr << "ERROR: " + message << std::endl;
    exit(1);
}

void Driver::help() {
    std::cout << std::endl;
    std::cout << "Commands:" << std::endl;
    std::cout << "    help                       Display this help message" << std::endl;
    std::cout << "    execute <file.svmb>        Execute bytecode" << std::endl;
    std::cout << "    assemble <file.svma>       Assemble assembly into bytecode" << std::endl;
    std::cout << "    compile [-O0] <file.sv>    Compile source code into assembly" << std::endl;
    std::cout << "    run [options] <file.sv>    Compile, assemble and execute source code" << std::endl;
    std::cout << std::endl;
    std::cout << "Run options:" << std::endl;
    std::cout << "    -a                         Save generated assembly to a .svma file" << std::endl;
    std::cout << "    -b                         Save generated bytecode to a .svmb file" << std::endl;
    std::cout << "    -O0                        Disable compiler optimisations" << std::endl;
    std::cout << std::endl;
    std::cout << "By default, compiler optimisations are enabled." << std::endl;
    std::cout << std::endl;
}

int Driver::execute(const char* filePath) {
    if (!isValidFileExtension(filePath, &BYTECODE_FILE_EXTENSION)) {
        return 1;
    }

    std::ifstream inputFile(filePath, std::ios::binary);
    if (!inputFile.is_open()) {
        std::cerr << "Error: could not open " << filePath << std::endl;
        return 1;
    }

    // read bytecode from file
    const std::vector<uint8_t> bytecode(
        (std::istreambuf_iterator<char>(inputFile)),
        std::istreambuf_iterator<char>()
    );

    // run bytecode in vm
    runVM(bytecode);
}

int Driver::assemble(const char* filePath) {
    if (!isValidFileExtension(filePath, &ASSEMBLY_FILE_EXTENSION)) {
        return 1;
    }

    const auto assembler = new assembler::Assembler();

    // assemble bytecode assembly
    std::vector<uint8_t> bytecode;
    try {
        bytecode = assembler->assemble(new std::filesystem::path(filePath));
    } catch (const AssemblerError& e) {
        std::cerr << e.generateMessage() << std::endl;
        return 1;
    }

    delete assembler;

    // replace .svma extension with .svmb
    std::filesystem::path outputFilePath(filePath);
    outputFilePath.replace_extension(BYTECODE_FILE_EXTENSION);

    return outputBytecodeFile(outputFilePath, bytecode);
}

int Driver::compile(const char* filePath, const OptimisationLevel optimisationLevel) {
    if (!isValidFileExtension(filePath, &PROGRAMMING_LANGUAGE_FILE_EXTENSION)) {
        return 1;
    }

    std::filesystem::path outputFilePath(filePath);

    const auto* compiler = new compiler::Compiler();
    const auto assembly = compiler->compile(readSourceCode(filePath), filePath, optimisationLevel);
    delete compiler;

    // replace .sv extension with .svma
    outputFilePath.replace_extension(ASSEMBLY_FILE_EXTENSION);

    return outputAssemblyFile(outputFilePath, assembly);
}

int Driver::run(const char *filePath, const bool outputAssembly, const bool outputByteCode, const OptimisationLevel optimisationLevel) {
    if (!isValidFileExtension(filePath, &PROGRAMMING_LANGUAGE_FILE_EXTENSION)) {
        return 1;
    }

    // replace .sv extension with .svma
    std::filesystem::path outputFilePath(filePath);

    // compile code
    const auto* compiler = new compiler::Compiler();
    const auto assembly = compiler->compile(readSourceCode(filePath), filePath, optimisationLevel);
    delete compiler;

    outputFilePath.replace_extension(ASSEMBLY_FILE_EXTENSION);

    if (outputAssembly) {
        // generate .svma file
        const int exitCode = outputAssemblyFile(outputFilePath, assembly);
        if (exitCode != 0) {
            return exitCode;
        }
    }

    std::string assemblyLanguage;
    for (const auto& line : assembly) {
        assemblyLanguage += line + "\n";
    }

    // assemble bytecode assembly
    const auto assembler = new assembler::Assembler();
    std::vector<uint8_t> bytecode;
    try {
        bytecode = assembler->assembleString(assemblyLanguage);
    } catch (const AssemblerError& e) {
        std::cerr << e.generateMessage() << std::endl;
        return 1;
    }
    delete assembler;

    outputFilePath.replace_extension(BYTECODE_FILE_EXTENSION);

    if (outputByteCode) {
        // generate .svmb file
        const int exitCode = outputBytecodeFile(outputFilePath, bytecode);
        if (exitCode != 0) {
            return exitCode;
        }
    }

    // run bytecode in vm
    runVM(bytecode);
}

void Driver::runVM(const std::vector<uint8_t>& bytecode) {
    // run bytecode in vm
    const auto vm = new VM();
    try {
        vm->run(&bytecode);
        exit(vm->getExitStatus());
    } catch (RuntimeError& e) {
        vm->handleRuntimeError(e);
        exit(vm->getExitStatus());
    }
}

std::string Driver::readSourceCode(const std::filesystem::path& path) {
    std::ifstream file(path, std::ios::binary);

    if (!file) {
        std::cerr << "Error: could not open " << path << std::endl;
        exit(EXIT_FAILURE);
    }

    return {
        std::istreambuf_iterator<char>(file),
        std::istreambuf_iterator<char>()
    };
}

int Driver::outputBytecodeFile(const std::filesystem::path& outputFilePath, const std::vector<uint8_t>& bytecode) {
    // generate output file from bytecode stored in vector
    std::ofstream outputFile(outputFilePath, std::ios::binary);
    if (!outputFile.is_open()) {
        std::cerr << "Error: could not create and open " << outputFilePath << std::endl;
        return 1;
    }

    outputFile.write(
        reinterpret_cast<const char*>(bytecode.data()),
        static_cast<std::streamsize>(bytecode.size())
    );

    outputFile << std::dec << "\n";
    outputFile.close();
    return 0;
}

int Driver::outputAssemblyFile(const std::filesystem::path& path, const std::vector<std::string>& assembly) {
    std::ofstream outputFile(path);

    if (!outputFile.is_open()) {
        std::cerr << "Error: could not create and open " << path << std::endl;
        return 1;
    }

    for (const auto& line : assembly) {
        outputFile << line << '\n';
    }
    return 0;
}

bool Driver::isValidFileExtension(const std::filesystem::path &filePath, const std::string_view* extension) {
    // validate file extension
    const std::filesystem::path path(filePath);
    if (path.extension() != *extension) {
        handleUnsupportedFileExtensionError(&path);
        return false;
    }
    return true;
}

void Driver::handleUnsupportedFileExtensionError(const std::filesystem::path* path) {
    std::cerr << "File extension \'"<< path->extension() << "\' is not supported" << std::endl;
}
